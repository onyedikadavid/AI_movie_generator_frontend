"use client";

import { Clapperboard, Layers, Scissors } from "lucide-react";
import type { SceneStyle } from "@/lib/types";

export const SCENE_STYLE_OPTIONS: { value: SceneStyle; title: string; blurb: string; Icon: typeof Clapperboard }[] = [
  {
    value: "whole",
    title: "Whole scene",
    blurb: "One clip per scene. The video model speaks the lines itself, so lips match. Needs the server's sound mode set to model voices.",
    Icon: Clapperboard,
  },
  {
    value: "shots",
    title: "Shot by shot",
    blurb: "The scene is broken into several short shots, each generated by the video model. More cuts, slower.",
    Icon: Scissors,
  },
  {
    value: "reuse",
    title: "Reuse footage",
    blurb: "One short clip per scene is cut into all its shots and the voices are added on top. Fastest, but lips won't match the words.",
    Icon: Layers,
  },
];

export function SceneStylePicker({
  value,
  onChange,
  disabled,
  busy,
}: {
  value: SceneStyle;
  onChange: (v: SceneStyle) => void;
  disabled?: boolean;
  busy?: boolean;
}) {
  return (
    <div role="radiogroup" aria-label="How each scene is built" className="grid grid-cols-1 gap-3 sm:grid-cols-3">
      {SCENE_STYLE_OPTIONS.map(({ value: v, title, blurb, Icon }) => {
        const selected = v === value;
        return (
          <button
            key={v}
            type="button"
            role="radio"
            aria-checked={selected}
            disabled={disabled || busy}
            onClick={() => !selected && onChange(v)}
            className={`flex flex-col gap-1 rounded-card border px-4 py-3 text-left transition disabled:cursor-not-allowed disabled:opacity-60 ${
              selected ? "border-tally bg-tally/10" : "border-ink-border bg-ink-surface hover:border-paper-faint"
            }`}
          >
            <span className={`inline-flex items-center gap-2 text-sm font-medium ${selected ? "text-tally" : "text-paper"}`}>
              <Icon className="h-4 w-4" /> {title}
            </span>
            <span className="text-xs text-paper-muted">{blurb}</span>
          </button>
        );
      })}
    </div>
  );
}
